CREATE DATABASE IF NOT EXISTS saferide CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE saferide;
CREATE TABLE IF NOT EXISTS users(
 id INT AUTO_INCREMENT PRIMARY KEY, username VARCHAR(30) NOT NULL UNIQUE, password_hash VARCHAR(255) NOT NULL,
 full_name VARCHAR(60) NOT NULL, role ENUM('admin','driver','parent') NOT NULL,
 failed_attempts TINYINT NOT NULL DEFAULT 0, locked_until DATETIME NULL);
CREATE TABLE IF NOT EXISTS vehicles(
 id INT AUTO_INCREMENT PRIMARY KEY, plate VARCHAR(10) NOT NULL UNIQUE, capacity SMALLINT NOT NULL CHECK (capacity BETWEEN 1 AND 60));
CREATE TABLE IF NOT EXISTS drivers(
 id INT AUTO_INCREMENT PRIMARY KEY, user_id INT NULL UNIQUE, name VARCHAR(60) NOT NULL, phone CHAR(10) NOT NULL, license VARCHAR(8) NOT NULL UNIQUE,
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL);
CREATE TABLE IF NOT EXISTS routes(
 id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(60) NOT NULL, depart_time TIME NOT NULL,
 vehicle_id INT NOT NULL, driver_id INT NOT NULL,
 FOREIGN KEY (vehicle_id) REFERENCES vehicles(id) ON DELETE RESTRICT,
 FOREIGN KEY (driver_id) REFERENCES drivers(id) ON DELETE RESTRICT);
CREATE TABLE IF NOT EXISTS stops(
 id INT AUTO_INCREMENT PRIMARY KEY, route_id INT NOT NULL, name VARCHAR(60) NOT NULL, seq TINYINT NOT NULL,
 FOREIGN KEY (route_id) REFERENCES routes(id) ON DELETE CASCADE);
CREATE TABLE IF NOT EXISTS students(
 id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(60) NOT NULL, grade VARCHAR(10) NOT NULL,
 parent_id INT NOT NULL, route_id INT NOT NULL, stop_id INT NOT NULL,
 FOREIGN KEY (parent_id) REFERENCES users(id) ON DELETE RESTRICT,
 FOREIGN KEY (route_id) REFERENCES routes(id) ON DELETE CASCADE,
 FOREIGN KEY (stop_id) REFERENCES stops(id) ON DELETE CASCADE);
CREATE TABLE IF NOT EXISTS attendance(
 id INT AUTO_INCREMENT PRIMARY KEY, student_id INT NOT NULL, att_date DATE NOT NULL, status ENUM('boarded','absent') NOT NULL,
 UNIQUE (student_id, att_date), FOREIGN KEY (student_id) REFERENCES students(id) ON DELETE CASCADE);
